// La bibliothèque pneumatique: how /chat answers. A question arrives in a capsule, the five
// closest index cards leave the catalogue, and a typewriter writes the answer from them only.
//   node build.mjs [--light]
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import * as k from "../_kit/iso-kit.mjs";
import { basePlate, f1, labelPlate, timelineLive, tools, writePage } from "../_shared.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));

// ---------------------------------------------------------------- truth (CLAUDE.md, rag/chain)
// The RAG index by chunk type (production, 2026-07); retrieve() takes k = 5 by exact cosine scan;
// the answer is generated by Groq openai/gpt-oss-120b at temperature 0.2.
const DRAWERS = [
  ["VOTES", 5105],
  ["DÉPUTÉS", 645],
  ["NOTABLES", 102],
  ["LOIS", 20],
  ["GROUPES", 12],
  ["SYNTHÈSE", 1],
];
const TOTAL = DRAWERS.reduce((a, [, n]) => a + n, 0);
const K = 5;
const PICKS = [0, 0, 0, 0, 1]; // the example: four vote cards and one deputy card
const QUESTION = "Comment l'Assemblée a-t-elle voté sur l'aide à mourir ?";

// ---------------------------------------------------------------- world
const WIDTH = 640;
const HEIGHT = 420;
const PLATE = { x: -156, y: -74, w: 312, d: 148, r: 9 };
const CAB = { x: -112, y: -42, w: 64, d: 50, r: 2 };
const DRAWER_H = 9;
const CAB_Z = 4;
const CAB_TOP = CAB_Z + DRAWER_H * DRAWERS.length;
const FRONT_Y = CAB.y + CAB.d;
const RAIL_Y = -12;
const RAIL_Z = 86;
const CAP_Z = 62; // capsule bottom
const CAP_STOPS = { start: -150, cab: -80, tw: 70 };
const TW = { x: 40, y: -30, w: 66, d: 46, r: 4 };
const PAPER = { x: 54, y: -27, w: 38, d: 2, r: 0.4 };

const P = k.fitProjection([...k.boxCorners(PLATE, -17, 0), [-150, RAIL_Y, RAIL_Z + 6], [110, RAIL_Y, RAIL_Z + 6]], WIDTH, HEIGHT, { pad: 22, azimuth: 50, elevation: 32 });
const { at, S, L, D, halo } = tools(P);
const drawerZ = (i) => CAB_TOP - (i + 1) * DRAWER_H; // drawer 0 on top

// ---------------------------------------------------------------- art
function cabinet() {
  const out = [halo(CAB, 5)];
  out.push(S(k.slabOf(k.insetPlan(CAB, -2), 0, CAB_Z, P, 3, 0.5), { tone: "lo" }));
  out.push(S(k.slabOf(CAB, CAB_Z, CAB_TOP - CAB_Z, P, 3, 0.8), { tone: "mid" }));
  out.push(S(k.slabOf(k.insetPlan(CAB, -1.5), CAB_TOP, 3, P, 3, 0.6), { tone: "mid" }));
  return out.join("");
}
// a drawer: its box (seen when open) and its front with a label holder and a pull
const drawerSvg = (i) => {
  const z = drawerZ(i);
  const out = [];
  const front = { x: CAB.x + 2, y: FRONT_Y - 1, w: CAB.w - 4, d: 2, r: 0.6 };
  out.push(S(k.slabOf(front, z + 0.6, DRAWER_H - 1.2, P, 2, 0.3), { tone: "mid" }));
  const m = k.sideMatrix([front.x + 6, FRONT_Y + 1], z + DRAWER_H / 2 + 1.2, P, "left");
  out.push(k.faceTextSvg(m, `${DRAWERS[i][0]} ${DRAWERS[i][1].toLocaleString("fr-FR")}`, { size: 2.6, tone: "mid" }));
  const pull = [front.x + front.w - 10, FRONT_Y + 1];
  out.push(S(k.slabOf({ x: pull[0] - 4, y: pull[1], w: 8, d: 1.6, r: 0.5 }, z + DRAWER_H / 2 - 1, 2, P, 2), { tone: "hi", crease: "lo" }));
  return out.join("");
};

function rail() {
  const out = [];
  for (const x of [-146, 104]) {
    out.push(S(k.slabOf({ x: x - 5, y: RAIL_Y - 5, w: 10, d: 10, r: 1.5 }, 0, 3, P, 3, 0.4), { tone: "mid" }));
    out.push(S(k.cylinder(x, RAIL_Y, 2.4, 3, RAIL_Z - 3, P, 18), { tone: "mid", crease: "none" }));
  }
  const beam = { x: -152, y: RAIL_Y - 3, w: 262, d: 6, r: 1 };
  out.push(S(k.slabOf(beam, RAIL_Z, 4, P, 3, 0.4), { tone: "mid" }));
  out.push(L(k.planOutline(k.insetPlan(beam, 1.4), RAIL_Z + 4, P, 3), { tone: "faint" }));
  return out.join("");
}
const capsuleSvg = () => [
  S(k.slabOf({ x: -2, y: RAIL_Y - 2, w: 4, d: 4, r: 0.8 }, CAP_Z + 18, RAIL_Z - CAP_Z - 18, P, 2), { tone: "mid", crease: "none" }),
  S(k.cylinder(0, RAIL_Y, 6, CAP_Z, 18, P, 28, 0.5), { tone: "hi", lit: true, inner: L(k.sideArc(0, RAIL_Y, 6, CAP_Z + 4, P, 20) + k.sideArc(0, RAIL_Y, 6, CAP_Z + 14, P, 20), { tone: "faint" }) }),
].join("");

function typewriter() {
  const out = [halo(TW, 5)];
  out.push(S(k.slabOf(TW, 0, 10, P, 4, 0.8), { tone: "mid" }));
  // carriage with platen at the back
  out.push(S(k.slabOf({ x: TW.x - 4, y: TW.y + 2, w: TW.w + 8, d: 12, r: 3 }, 10, 10, P, 4, 0.6), { tone: "mid" }));
  for (const x of [TW.x - 7, TW.x + TW.w + 3]) { out.push(S(k.cylinder(x + 2, TW.y + 8, 3.2, 12, 6, P, 18), { tone: "mid" })); out.push(L(k.knurl(x + 2, TW.y + 8, 3.2, 12, 18, 16, P), { tone: "lo" })); }
  const deck = { x: TW.x + 4, y: TW.y + 16, w: TW.w - 8, d: TW.d - 20, r: 2 };
  out.push(S(k.slabOf(deck, 10, 2, P, 3, 0.4), { tone: "mid" }));
  // keys: four rows of round keys
  for (let row = 0; row < 4; row++)
    for (let c = 0; c < 10; c++) {
      const x = deck.x + 6 + c * 5.4 + row * 1.4, y = deck.y + 4 + row * 5.4;
      out.push(S(k.cylinder(x, y, 1.8, 12, 1.6, P, 12), { tone: "hi", crease: "lo" }));
    }
  return out.join("");
}
const cardSvg = (i) => `<g data-card="${i}" opacity="0">${S(k.slabOf({ x: -4, y: -0.6, w: 8, d: 1.2, r: 0.3 }, 0, 6, P, 2), { tone: "hi", crease: "lo" })}</g>`;

// ---------------------------------------------------------------- live
const T = { arrive: 1.4, open: 2.0, fly: 3.8, close: 4.4, ride: 6.2, type: 9.4, end: 12.4 };
const LOOP = T.end;
const svg = k.figureSvg({
  width: WIDTH,
  height: HEIGHT,
  label: `Une bibliothèque pneumatique. Une question arrive en capsule au-dessus d'un fichier de ${TOTAL} fiches en six tiroirs. Les cinq fiches les plus proches en sortent, voyagent jusqu'à une machine à écrire, qui rédige la réponse à partir d'elles seules.`,
  body: [
    basePlate(P, PLATE),
    labelPlate(P, { x: 100, y: 52, w: 44, d: 14, r: 1.5 }),
    rail(),
    cabinet(),
    // closed drawers first, then the ones that open, lower before upper so each sits over the one below
    ...DRAWERS.map((_, i) => i)
      .sort((a, b) => (PICKS.includes(a) - PICKS.includes(b)) || b - a)
      .map((i) => `<g data-dbox="${i}"></g><g data-drawer="${i}">${drawerSvg(i)}</g>`),
    typewriter(),
    `<g data-part="paper"></g>`,
    `<g data-part="capsule">${capsuleSvg()}</g>`,
    PICKS.map((_, i) => cardSvg(i)).join(""),
  ],
});

const live = `
const P = ${JSON.stringify(P)};
const T = ${JSON.stringify(T)};
const PICKS = ${JSON.stringify(PICKS)}, K = ${K}, TOTAL = ${TOTAL};
const CAP = ${JSON.stringify(CAP_STOPS)}, RAIL_Y = ${RAIL_Y}, CAP_Z = ${CAP_Z};
const CAB = ${JSON.stringify(CAB)}, FRONT_Y = ${FRONT_Y}, PAPER = ${JSON.stringify(PAPER)};
const DZ = ${JSON.stringify(DRAWERS.map((_, i) => drawerZ(i)))}, DRAWER_H = ${DRAWER_H};
const QUESTION = ${JSON.stringify(QUESTION)};
const drawers = [...document.querySelectorAll("[data-drawer]")].sort((a, b) => a.dataset.drawer - b.dataset.drawer);
const dboxes = [...document.querySelectorAll("[data-dbox]")].sort((a, b) => a.dataset.dbox - b.dataset.dbox);
const shown = DZ.map(() => -1);
function pullOut(i, d) {
  const q = Math.round(d * 2) / 2;
  if (q === shown[i]) return;
  shown[i] = q;
  if (q < 0.5) { dboxes[i].innerHTML = ""; return; }
  const z = DZ[i];
  const box = { x: CAB.x + 4, y: FRONT_Y - 1, w: CAB.w - 8, d: q, r: 0.6 };
  const lines = [];
  for (let y = box.y + 2; y < box.y + q - 1; y += 2.2) lines.push(onTop([[box.x + 4, y], [box.x + box.w - 4, y]], z + DRAWER_H - 1.4, P));
  dboxes[i].innerHTML = solidSvg(slabOf(box, z + 1, DRAWER_H - 2.4, P, 2), { tone: "hi", crease: "lo" }) + lineSvg(lines.join(""), { tone: "lo" });
}
const cards = [...document.querySelectorAll("[data-card]")];
const capsule = document.querySelector('[data-part="capsule"]');
const paper = document.querySelector('[data-part="paper"]');
const readout = document.querySelector("[data-readout]");
const ease = (u) => (u <= 0 ? 0 : u >= 1 ? 1 : u < 0.5 ? 2 * u * u : 1 - 2 * (1 - u) ** 2);
const span = (t, a, b) => ease((t - a) / (b - a));
let paperH = -1;
function setPaper(h) {
  const q = Math.round(h * 4) / 4;
  if (q === paperH) return;
  paperH = q;
  if (q <= 0) { paper.innerHTML = ""; return; }
  const lines = [];
  for (let z = 22; z < 20 + q - 1; z += 2.4) lines.push(lineSvg(segment([PAPER.x + 4, PAPER.y + PAPER.d, z], [PAPER.x + PAPER.w - 4 - (z * 7 % 11), PAPER.y + PAPER.d, z], P), { tone: "lo", free: true }));
  paper.innerHTML = solidSvg(slabOf(PAPER, 20, q, P, 2), { tone: "hi", crease: "none" }) + lines.join("");
}
function draw(t) {
  // capsule along the rail
  let cx = CAP.start;
  if (t < T.arrive) cx = CAP.start + (CAP.cab - CAP.start) * span(t, 0, T.arrive);
  else if (t < T.close) cx = CAP.cab;
  else if (t < T.ride) cx = CAP.cab + (CAP.tw - CAP.cab) * span(t, T.close, T.ride);
  else cx = CAP.tw;
  capsule.setAttribute("transform", translateAlong(P, [cx, 0, 0]));
  // drawers open while the cards leave
  const open = t < T.open ? span(t, T.arrive, T.open) : t < T.fly ? 1 : 1 - span(t, T.fly, T.close);
  drawers.forEach((el, i) => { const d = PICKS.includes(i) ? open * 16 : 0; el.setAttribute("transform", translateAlong(P, [0, d, 0])); pullOut(i, d); });
  // each card rises from its drawer into the capsule, one after another
  cards.forEach((el, i) => {
    const a = T.open + i * 0.3, b = a + 0.8;
    const u = span(t, a, b);
    if (t < a || t > T.close) { el.setAttribute("opacity", "0"); return; }
    const d = PICKS[i];
    const from = [CAB.x + 14 + i * 9, CAB.y + 30 + 16, DZ[d] + DRAWER_H];
    const to = [CAP.cab, RAIL_Y, CAP_Z + 4];
    const p = [from[0] + (to[0] - from[0]) * u, from[1] + (to[1] - from[1]) * u, from[2] + (to[2] - from[2]) * u + 18 * Math.sin(Math.PI * u)];
    el.setAttribute("opacity", u >= 1 ? "0" : "1");
    el.setAttribute("transform", translateAlong(P, p));
  });
  setPaper(t < T.ride ? 0 : 22 * span(t, T.ride, T.type));
  const inCapsule = cards.filter((_, i) => t >= T.open + i * 0.3 + 0.8).length;
  let text;
  if (t < T.arrive) text = "question · « " + QUESTION + " »";
  else if (t < T.close) text = "recherche · " + Math.min(K, inCapsule) + " / " + K + " fiches les plus proches parmi " + TOTAL.toLocaleString("fr-FR");
  else if (t < T.ride) text = "les " + K + " fiches partent vers la rédaction";
  else if (t < T.type) text = "rédaction · Groq gpt-oss-120b, température 0,2";
  else text = "réponse · " + K + " sources citées";
  if (readout.textContent !== text) readout.textContent = text;
}
${timelineLive({ loop: LOOP, scrubFrom: 0, scrubTo: T.type + 0.4, step: 0.5, rest: T.type + 0.4 })}
`;

writePage({
  here: HERE,
  name: "bibliotheque",
  title: "La bibliothèque pneumatique",
  fig: "Fig 6",
  hint: "Survolez pour suivre la question",
  readout: "question",
  keys: [
    { mark: "lit", label: "La capsule : la question, puis ses cinq fiches" },
    { mark: "raised", label: "Six tiroirs, un par type de fiche, avec leur nombre réel" },
  ],
  caption: `Comment le chat de MonÉlu répond. L'index compte ${TOTAL.toLocaleString("fr-FR")} fiches : une par scrutin, par député, par groupe, plus des synthèses. La question est comparée à toutes, par similarité cosinus exacte, et les ${K} plus proches sont seules transmises au modèle, qui rédige à partir d'elles et les cite. La question et le choix des fiches (quatre scrutins, un député) sont un exemple.`,
  svg,
  ariaLabel: "La bibliothèque pneumatique : flèches gauche et droite pour suivre la question",
  ariaValue: "Une question, cinq fiches, une réponse citée",
  live,
});
